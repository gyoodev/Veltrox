export const OTHER_MAKE_OPTION = "__OTHER_MAKE__";
export const OTHER_MODEL_OPTION = "__OTHER_MODEL__";

/**
 * Returns all car makes sorted alphabetically.
 */
export function getAllCarMakes(): string[] {
  return CAR_MAKES_CATALOG.map((m) => m.name).sort((a, b) =>
    a.localeCompare(b, undefined, { sensitivity: "base" })
  );
}

/**
 * Returns the models for a given make name (case-insensitive).
 */
export function getModelsForMake(makeName: string): string[] {
  if (!makeName || makeName === OTHER_MAKE_OPTION) return [];
  const found = CAR_MAKES_CATALOG.find(
    (m) => m.name.toLowerCase() === makeName.trim().toLowerCase()
  );
  return found ? [...found.models] : [];
}

/**
 * Checks if a make is recognized in the catalog.
 */
export function isKnownMake(makeName: string): boolean {
  if (!makeName) return false;
  return CAR_MAKES_CATALOG.some(
    (m) => m.name.toLowerCase() === makeName.trim().toLowerCase()
  );
}

